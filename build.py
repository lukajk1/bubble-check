"""Build questions.js from research/*.json.

SPOILER WARNING: research/*.json holds every answer in plain text. Don't open it if you
want to take the quiz.

questions.js stores the data base64-encoded so the answers don't show at a glance in the
page source or the repo. Run:  python build.py
"""
import base64
import json
import pathlib
import sys
from datetime import date

ROOT = pathlib.Path(__file__).parent
CATEGORY_ORDER = [
    "Politics & Beliefs",
    "Music",
    "Tech & Internet",
    "Shopping, Food & Style",
    "Games, Screen & Sports",
    "Lifestyle & Time",
]


def validate(q):
    p = f"[{q.get('id')}]"
    for k in ("id", "category", "type", "prompt", "explanation", "source"):
        assert q.get(k), f"{p} missing {k}"
    assert q["category"] in CATEGORY_ORDER, f"{p} unknown category {q['category']}"
    assert q["source"].get("url", "").startswith("http"), f"{p} bad source url"
    t = q["type"]
    if t == "rank":
        items = q["items"]
        assert len(items) == 4, f"{p} rank needs 4 items"
        vals = sorted((i["value"] for i in items), reverse=True)
        assert len(set(vals)) == 4, f"{p} tied values"
    elif t == "bins":
        assert len(q["bins"]) == 4 and 0 <= q["answerBin"] < 4, f"{p} bad bins"
        assert q.get("answer") is not None, f"{p} bins needs the true number"
    elif t == "percent":
        assert 0 <= q["answer"] <= 100, f"{p} percent out of range"
    elif t == "number":
        assert q["min"] <= q["answer"] <= q["max"], f"{p} number out of range"
    else:
        raise AssertionError(f"{p} unknown type {t}")


def main():
    qs = []
    for f in sorted((ROOT / "research").glob("*.json")):
        qs += json.loads(f.read_text(encoding="utf-8"))
    # "drop": failed fact-checking. "reserve": fine, but left out to keep the quiz near 10 minutes.
    qs = [q for q in qs if not q.get("drop") and not q.get("reserve")]
    ids = [q["id"] for q in qs]
    assert len(ids) == len(set(ids)), "duplicate ids"
    for q in qs:
        validate(q)

    # Interleave topics so consecutive questions vary.
    buckets = {c: [q for q in qs if q["category"] == c] for c in CATEGORY_ORDER}
    ordered = []
    while any(buckets.values()):
        for c in CATEGORY_ORDER:
            if buckets[c]:
                ordered.append(buckets[c].pop(0))

    keep = ("id", "category", "type", "prompt", "rankLabel", "rankAscending", "items", "bins",
            "answerBin", "answer", "unit", "min", "max", "step", "explanation", "source",
            "extraSources", "caveat")
    data = {
        "version": date.today().isoformat(),
        "questions": [{k: q[k] for k in keep if k in q} for q in ordered],
    }
    blob = base64.b64encode(json.dumps(data, ensure_ascii=False).encode("utf-8")).decode("ascii")
    (ROOT / "questions.js").write_text(
        "// Generated by build.py. Encoded so the answers don't spoil at a glance.\n"
        f'window.__BUBBLE_DATA__ = "{blob}";\n', encoding="utf-8")
    counts = {c: sum(q["category"] == c for q in ordered) for c in CATEGORY_ORDER}
    print(f"{len(ordered)} questions -> questions.js", counts, file=sys.stderr)


if __name__ == "__main__":
    main()
